export const meta = {
  name: 'portfolio-check',
  description: 'ตรวจการแก้ไขของแอปแฟ้มสะสมงานเป็นลำดับขั้น: สำรวจด้วยโมเดลเร็ว ตรวจด้วยโมเดลกลาง แล้วยืนยันด้วยโมเดลละเอียด',
  whenToUse: 'ก่อน commit หรือก่อนส่งงานให้ทีม เมื่ออยากรู้ว่าการแก้รอบนี้ขัดกติกาของโปรเจกต์หรือมีบั๊กหรือไม่ ส่ง args เป็นช่วง diff ได้ เช่น "HEAD~1" (ค่าเริ่มต้นคือสิ่งที่ยังไม่ commit)',
  phases: [
    { title: 'สำรวจ', detail: 'ดูว่าอะไรเปลี่ยนและมันอยู่ตรงไหน (haiku)' },
    { title: 'ตรวจ', detail: 'ตรวจกติกาโปรเจกต์รายด้าน + ทดสอบในเบราว์เซอร์ (sonnet)' },
    { title: 'ยืนยัน', detail: 'พยายามหักล้างข้อค้นพบ เหลือเฉพาะที่จริง (opus)' }
  ]
};

const target = typeof args === 'string' && args.trim() ? args.trim() : '';
const diffCmd = target ? `git diff ${target} --stat && git diff ${target}` : 'git status --short && git diff';

const FINDINGS = {
  type: 'object',
  properties: {
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          title: { type: 'string' },
          where: { type: 'string', description: 'path:line' },
          why: { type: 'string', description: 'จะพังอย่างไรในทางปฏิบัติ' },
          severity: { type: 'string', enum: ['สูง', 'กลาง', 'ต่ำ'] }
        },
        required: ['title', 'where', 'why', 'severity']
      }
    }
  },
  required: ['findings']
};

/* ---- ขั้นที่ 1: สำรวจด้วยโมเดลเร็ว ---- */
phase('สำรวจ');
const facts = await agent(
  `รัน \`${diffCmd}\` แล้วสรุปว่า (1) ไฟล์ไหนเปลี่ยนบ้าง (2) การเปลี่ยนแต่ละก้อนอยู่ในหัวข้อไหนของ portfolio/index.html ` +
  `(ดูจากคอมเมนต์หัวข้อที่มีเลขกำกับ เช่น "13b) หน้า Logbook") (3) ฟังก์ชันที่ถูกแตะมีชื่อว่าอะไรบ้าง พร้อม path:line ` +
  `ตอบเป็นรายการสั้น ๆ ไม่ต้องวิเคราะห์`,
  { agentType: 'ortho-scan', label: 'สำรวจการเปลี่ยนแปลง', phase: 'สำรวจ' }
);
log('สำรวจเสร็จ — ส่งต่อให้ผู้ตรวจ');

/* ---- ขั้นที่ 2: ตรวจรายด้านพร้อมกัน + ทดสอบจริงในเบราว์เซอร์ ---- */
phase('ตรวจ');
const LENSES = [
  { key: 'ความเป็นส่วนตัวของข้อมูลผู้ป่วย', ask: 'ดูว่ามีเส้นทางใดที่ทำให้ชื่อผู้ป่วย HN อายุ หรือเพศ ออกจากเครื่องหรือข้ามระดับที่ตั้งไว้' },
  { key: 'สิทธิ์การเข้าถึงตามบทบาท', ask: 'ดูว่าการกรองข้อมูลทำที่ชั้นข้อมูลจริงหรือแค่ซ่อนปุ่ม และมีทางใดที่บทบาทหนึ่งเห็นหรือแก้ของอีกบทบาทได้' },
  { key: 'ความถูกต้องของตรรกะและการซิงก์', ask: 'ดูตรรกะที่เปลี่ยน ว่าคำนวณผิด ทับข้อมูล หรือทำให้ข้อมูลหายเงียบ ๆ ได้หรือไม่' },
  { key: 'กติกาไฟล์เดียวและกับดักที่เคยเจอ', ask: 'ดูว่ามี dependency ภายนอก การเรียกเครือข่ายที่ไม่ได้ตั้งใจ หรือกับดักที่เคยเจอในโปรเจกต์นี้กลับมาอีกหรือไม่' }
];

const reviews = await parallel(LENSES.map(l => () =>
  agent(
    `นี่คือสิ่งที่เปลี่ยนในรอบนี้:\n\n${facts}\n\n` +
    `ตรวจในมุม "${l.key}" — ${l.ask}\n` +
    `ใช้ \`${diffCmd}\` ดูของจริงประกอบ รายงานเฉพาะข้อที่มีหลักฐานในโค้ด`,
    { agentType: 'ortho-review', label: `ตรวจ: ${l.key}`, phase: 'ตรวจ', schema: FINDINGS }
  )
));

const browser = await agent(
  `ทดสอบว่าแอปยังทำงานได้จริงหลังการแก้รอบนี้ โดยดูจากสิ่งที่เปลี่ยน:\n\n${facts}\n\n` +
  `อย่างน้อยต้องครอบคลุม: หน้าเปิดได้ไม่มี console error, ล็อกอินได้ทั้งสามบทบาท, ` +
  `และหน้าที่เกี่ยวกับสิ่งที่แก้รอบนี้ยังแสดงผลถูกต้อง`,
  { agentType: 'ortho-test', label: 'ทดสอบในเบราว์เซอร์', phase: 'ตรวจ' }
);

const all = reviews.filter(Boolean).flatMap(r => r.findings || []);
log(`ผู้ตรวจพบทั้งหมด ${all.length} ข้อ — ส่งให้ขั้นยืนยัน`);

/* ---- ขั้นที่ 3: ยืนยันด้วยโมเดลละเอียด ---- */
phase('ยืนยัน');
const verdict = await agent(
  `ข้อค้นพบจากผู้ตรวจ (${all.length} ข้อ):\n${JSON.stringify(all, null, 1)}\n\n` +
  `ผลทดสอบในเบราว์เซอร์:\n${browser}\n\n` +
  `ตรวจทีละข้อแบบพยายามหักล้าง เหลือเฉพาะข้อที่ยืนยันได้ แล้วสรุปเป็นรายการที่ลงมือแก้ต่อได้ ` +
  `เรียงตามผลกระทบ พร้อมทางแก้ที่เล็กที่สุดของแต่ละข้อ`,
  { agentType: 'ortho-verify', label: 'ยืนยันข้อค้นพบ', phase: 'ยืนยัน' }
);

return { สำรวจ: facts, พบก่อนยืนยัน: all.length, ทดสอบ: browser, สรุป: verdict };
